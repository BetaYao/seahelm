macro_rules! abi {
    ($rust:expr, $value:literal, $c:literal) => {
        const _: () = assert!(($rust) as i64 == $value, $c);
    };
}
macro_rules! abi_size {
    ($t:ty, $n:literal, $c:literal) => {
        const _: () = assert!(std::mem::size_of::<$t>() == $n, $c);
    };
}
macro_rules! abi_offset {
    ($t:ty, $field:ident, $n:literal, $c:literal, $cfield:literal) => {
        const _: () = assert!(std::mem::offset_of!($t, $field) == $n, $c);
    };
}

