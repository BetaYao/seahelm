//! The libghostty-vt ABI this crate is written against: every number the
//! bindings use, every struct they pass, named as the C headers name them.
//!
//! Each line is checked twice: here, at compile time, against the Rust
//! declarations, and by `build.rs`, which turns this file into C
//! `_Static_assert`s and compiles them against the headers of the library
//! being linked. A value or a layout that moves upstream fails the build
//! instead of corrupting calls.
//!
//! The forms are read by `build.rs`: one per line, as written below.

#![allow(clippy::unnecessary_cast)]

use std::os::raw::c_int;

